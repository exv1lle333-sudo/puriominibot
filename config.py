# ============ PURIO SHOP / КОСМЕТИКА / ГЕЙМИФИКАЦИЯ 2.0 ============
# Ценовая политика построена вокруг уже существующего курса обмена (см. выше:
# 1000 Purio Points = 1₽, тариф 30 дней = 99₽ ≈ 99 000 очков, т.е. "стоимость"
# одного дня VPN в очках ≈ 3 300 ✦). Она специально сделана так, чтобы:
#   1) Косметика (скины/рамки/эффекты/титулы/бейджи) НИЧЕГО не стоит нам в
#      реальных деньгах — это чистый "поинт-синк": чем больше игроки тратят
#      очки на неё, тем меньше они выводят в рубли через обмен, и тем выгоднее
#      это боту. Поэтому цены на косметику НАМЕРЕННО невысокие и достижимые.
#   2) У всех "гэмблинг"-механик (Mystery Box, Колесо удачи) заложена комиссия
#      казино (house edge), как и у остальных игр Purio Casino — в среднем
#      игрок получает обратно МЕНЬШЕ очков, чем потратил.
#   3) Бесплатные раздачи (ежедневный кейс) по ценности сопоставимы с наградой
#      за серию входов — то есть это бонус за вовлечённость, а не источник
#      значимого дохода в очках.
#   4) Бустеры ускоряют получение XP (уровень дракона / прогресс), а НЕ Purio
#      Points — поэтому они не увеличивают количество очков в обороте и не
#      бьют по марже обмена очков на рубли.

